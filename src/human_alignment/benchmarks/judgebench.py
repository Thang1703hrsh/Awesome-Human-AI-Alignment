"""JudgeBench (Tan et al., 2025): can a judge tell a correct answer from an incorrect one on hard problems?

Scoring follows the official ``run_judge.py`` and ``utils/metrics.py``:

* LLM judges see every pair twice, ``(A, B)`` and ``(B, A)``; the second decision is flipped back. Each trial adds
  +1 if it matches the label and −1 if it matches the flipped label (ties and failures add 0), and a pair is
  correct only when the sum is positive. A judge that guesses therefore scores below 50%.
* Reward models score each response once (single game): ``A>B`` if ``score_A > score_B`` else ``B>A`` (the source
  breaks exact ties towards B); chance is 50%.
* Categories come from ``source``: ``mmlu-pro*`` knowledge, ``livebench-reasoning``, ``livebench-math``,
  ``livecodebench`` coding. The ``gpt`` split has 350 pairs generated by GPT-4o, the ``claude`` split 270.
"""

from __future__ import annotations

from collections import defaultdict
from typing import Any, Callable, Sequence

from human_alignment.benchmarks.common import load_hf_split, score_pairs, take, wilson_interval

DATASET = "ScalerLab/JudgeBench"
CATEGORIES = (
    ("knowledge", "mmlu-pro"),
    ("reasoning", "livebench-reasoning"),
    ("math", "livebench-math"),
    ("coding", "livecodebench"),
)

# ``utils/templates/vanilla_prompt.jinja2`` (rendered; the source parses only these two exact answers).
VANILLA_PROMPT = """You are a helpful assistant in evaluating the quality of the outputs for a given instruction. Your goal is to select the best output for the given instruction.
Select the Output (a) or Output (b) that is better for the given instruction. The two outputs are generated by two different AI chatbots respectively.
Do NOT provide any explanation for your choice.
Do NOT say both / neither are good.
You should answer using ONLY "Output (a)" or "Output (b)". Do NOT output any other words.
# Instruction:
{question}
# Output (a):
{answer_a}
# Output (b):
{answer_b}
# Which is better, Output (a) or Output (b)? Your response should be either "Output (a)" or "Output (b)":"""

Decision = str | None  # "A>B", "B>A", "A=B" or None (failed / unparseable)
PairwiseJudge = Callable[[str, str, str], Decision]


def load_judgebench(split: str = "gpt", limit: int | None = None, revision: str | None = None) -> list[dict]:
    if split not in ("gpt", "claude"):
        raise ValueError("JudgeBench splits are 'gpt' and 'claude'")
    return take(load_hf_split(DATASET, split, revision=revision), limit)


def category(source: str) -> str:
    for name, prefix in CATEGORIES:
        if source.startswith(prefix):
            return name
    return "other"


def flip(decision: Decision) -> Decision:
    return {"A>B": "B>A", "B>A": "A>B"}.get(decision, decision) if decision else decision


def parse_vanilla(text: str | None) -> Decision:
    text = (text or "").strip()
    return {"Output (a)": "A>B", "Output (b)": "B>A"}.get(text)


def vote(label: str, first: Decision, second_flipped: Decision) -> int:
    """Official two-trial vote: +1 per trial equal to the label, −1 per trial equal to the flipped label."""
    return sum((d == label) - (d == flip(label)) for d in (first, second_flipped))


def summarize_judgebench(rows: Sequence[dict]) -> dict:
    """Accuracy overall and per category, with Wilson 95% intervals and consistency counts."""
    groups: dict[str, list[dict]] = defaultdict(list)
    for row in rows:
        groups[category(row["source"])].append(row)
        groups["overall"].append(row)
    out: dict[str, Any] = {"benchmark": "JudgeBench", "categories": {}}
    for name, items in groups.items():
        correct = sum(r["correct"] for r in items)
        stats = {
            "count": len(items),
            "accuracy": correct / len(items),
            "ci95": wilson_interval(correct, len(items)),
        }
        if all("decisions" in r for r in items):
            stats["inconsistent"] = sum(r["decisions"][0] != r["decisions"][1] for r in items)
            stats["failed_trials"] = sum(d is None for r in items for d in r["decisions"])
        if name == "overall":
            out["overall"] = stats
        else:
            out["categories"][name] = stats
    out["protocol"] = "double game (order-swapped vote)" if all("decisions" in r for r in rows) else "single game"
    return out


def evaluate_judgebench_with_judge(
    pairs: Sequence[dict], judge: PairwiseJudge, reverse_order: bool = True
) -> tuple[list[dict], dict]:
    """``judge(question, response_a, response_b)`` returns ``A>B``, ``B>A``, ``A=B`` or ``None``."""
    rows = []
    for pair in pairs:
        first = judge(pair["question"], pair["response_A"], pair["response_B"])
        row = {k: pair[k] for k in ("pair_id", "source", "label")}
        if reverse_order:
            second = flip(judge(pair["question"], pair["response_B"], pair["response_A"]))
            row["decisions"] = [first, second]
            row["correct"] = vote(pair["label"], first, second) > 0
        else:
            row["decision"] = first
            row["correct"] = first == pair["label"]
        rows.append(row)
    return rows, summarize_judgebench(rows)


def evaluate_judgebench_with_reward_model(pairs: Sequence[dict], scorer: Any) -> tuple[list[dict], dict]:
    """Single-game reward-model protocol: each response is scored once."""
    flat = [(p["question"], p[key]) for p in pairs for key in ("response_A", "response_B")]
    values = score_pairs(scorer, flat)
    rows = []
    for i, pair in enumerate(pairs):
        score_a, score_b = values[2 * i], values[2 * i + 1]
        decision = "A>B" if score_a > score_b else "B>A"
        rows.append(
            {
                "pair_id": pair["pair_id"],
                "source": pair["source"],
                "label": pair["label"],
                "scores": [score_a, score_b],
                "decision": decision,
                "correct": decision == pair["label"],
            }
        )
    return rows, summarize_judgebench(rows)


def openai_vanilla_judge(client: Any, model: str) -> PairwiseJudge:
    """The source's vanilla judge (temperature 0, top-p 1, 1024 tokens) over an OpenAI-compatible client."""

    def judge(question: str, answer_a: str, answer_b: str) -> Decision:
        try:
            response = client.chat.completions.create(
                model=model,
                messages=[
                    {
                        "role": "user",
                        "content": VANILLA_PROMPT.format(question=question, answer_a=answer_a, answer_b=answer_b),
                    }
                ],
                temperature=0.0,
                top_p=1.0,
                max_tokens=1024,
            )
        except Exception:  # noqa: BLE001 - a failed call is a null judgment, as in the source
            return None
        return parse_vanilla(response.choices[0].message.content)

    return judge
